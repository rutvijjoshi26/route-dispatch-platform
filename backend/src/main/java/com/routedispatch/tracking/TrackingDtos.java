package com.routedispatch.tracking;

import com.routedispatch.plan.EventOutcome;
import com.routedispatch.plan.StopEventType;
import com.routedispatch.plan.StopStatus;
import jakarta.validation.Valid;
import jakarta.validation.constraints.DecimalMax;
import jakarta.validation.constraints.DecimalMin;
import jakarta.validation.constraints.NotEmpty;
import jakarta.validation.constraints.NotNull;
import jakarta.validation.constraints.Size;
import java.time.Instant;
import java.util.List;
import java.util.UUID;

/** Request and response bodies of the driver and tracking APIs. */
public final class TrackingDtos {

    /** One GPS fix. {@code pingId} is generated by the device so retries are recognized. */
    public record PingRequest(
            @NotNull UUID pingId,
            @NotNull Instant recordedAt,
            @NotNull @DecimalMin("-90") @DecimalMax("90") Double lat,
            @NotNull @DecimalMin("-180") @DecimalMax("180") Double lon,
            @DecimalMin("0") @DecimalMax("90") Float speedMps,
            @DecimalMin("0") @DecimalMax("360") Float headingDeg) {
    }

    /** Devices buffer pings while offline and send them in batches. */
    public record PingBatch(@NotEmpty @Size(max = 500) List<@Valid @NotNull PingRequest> pings) {
    }

    public record IngestResult(int accepted, int duplicates, boolean positionUpdated) {
    }

    public record StopEventRequest(@NotNull UUID eventId, @NotNull StopEventType type, @NotNull Instant occurredAt,
                                   @Size(max = 255) String note) {
    }

    public record EventResult(UUID eventId, long stopId, EventOutcome outcome, StopStatus status, boolean duplicate) {
    }

    public record VehiclePositionView(long vehicleId, double lat, double lon, Float speedMps, Float headingDeg,
                                      Instant recordedAt) {
    }

    public record NearbyVehicleView(long vehicleId, double lat, double lon, Instant recordedAt, double distanceMeters) {
    }

    public record TrailView(long vehicleId, List<double[]> path) {
    }

    private TrackingDtos() {
    }
}
